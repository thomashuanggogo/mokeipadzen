  let lang = 'zh';
  try { lang = localStorage.getItem('moke-lang') === 'en' ? 'en' : 'zh'; } catch (e) {}
  const origText = new WeakMap();
  const origAttr = new WeakMap();

  function t(s, vars) {
    if (typeof s !== 'string') return s;
    const sec = s.match(/^段落 (\d+)$/); // 段落標籤存的是繁中，顯示時才翻譯
    if (sec && lang === 'en') return 'Section ' + sec[1];
    let out = (lang === 'en' && DICT[s]) ? DICT[s] : s;
    if (vars) for (const k in vars) out = out.split('{' + k + '}').join(String(vars[k]));
    return out;
  }

  function applyI18n(root) {
    root = root || document.body;
    if (!root || !document.createTreeWalker) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(n) {
        if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const p = n.parentElement;
        if (!p || (p.closest && p.closest('script, style'))) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const n of nodes) {
      const cur = n.nodeValue;
      let orig = origText.get(n);
      if (orig === undefined) { orig = cur; origText.set(n, cur); }
      else if (cur !== orig && cur !== (DICT[orig.trim()] ? orig.replace(orig.trim(), DICT[orig.trim()]) : orig)) {
        orig = cur; origText.set(n, cur); // 內容已被程式改寫 → 以現值為新的原文
      }
      if (lang === 'en') {
        const trimmed = orig.trim();
        if (DICT[trimmed]) n.nodeValue = orig.replace(trimmed, DICT[trimmed]);
      } else if (n.nodeValue !== orig) {
        n.nodeValue = orig;
      }
    }
    if (root.querySelectorAll) {
      root.querySelectorAll('[title], [placeholder]').forEach(el => {
        let o = origAttr.get(el);
        if (!o) { o = { title: el.getAttribute('title'), ph: el.getAttribute('placeholder') }; origAttr.set(el, o); }
        for (const [attr, key] of [['title', 'title'], ['placeholder', 'ph']]) {
          const base = o[key];
          if (base == null) continue;
          const cur = el.getAttribute(attr);
          const translated = DICT[base] || base;
          if (cur !== base && cur !== translated) { o[key] = cur; continue; } // 程式改過 → 採現值為原文
          el.setAttribute(attr, lang === 'en' ? translated : base);
        }
      });
    }
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-Hant';
    const btn = document.getElementById('btn-lang');
    const want = lang === 'en' ? '中文' : 'EN';
    if (btn && btn.textContent !== want) btn.textContent = want; // 沒變就不寫：textContent 賦值必觸發 MutationObserver，會無限迴圈
  }

  function setLang(l) {
    lang = l === 'en' ? 'en' : 'zh';
    try { localStorage.setItem('moke-lang', lang); } catch (e) {}
    applyI18n();
  }

  window.MokeI18n = { t, applyI18n, setLang, get lang() { return lang; }, DICT };
  window.t = t;

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => applyI18n());
  else applyI18n();
  // 動態插入的節點（課程清單、貼紙格、toast）自動套用
  const mo = new MutationObserver(muts => {
    for (const m of muts) for (const n of m.addedNodes) {
      if (n.nodeType === 1) applyI18n(n);
      else if (n.nodeType === 3 && n.parentElement) applyI18n(n.parentElement);
    }
  });
  const startObs = () => { if (document.body) mo.observe(document.body, { childList: true, subtree: true }); };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', startObs);
  else startObs();
